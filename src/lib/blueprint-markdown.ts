import { Blueprint } from "./types";

const SECTION_TITLES: Record<string, string> = {
  executiveSummary: "Executive Summary",
  userPersonas: "User Personas",
  featureBreakdown: "Feature Breakdown",
  userFlows: "User Flows",
  dataModel: "Data Model",
  techStackRecommendations: "Tech Stack Recommendations",
  monetizationStrategy: "Monetization Strategy",
  mvpScope: "MVP Scope",
  architectureOverview: "Architecture Overview",
  designDirection: "Design Direction",
};

const SECTION_ORDER = [
  "executiveSummary",
  "userPersonas",
  "featureBreakdown",
  "userFlows",
  "dataModel",
  "techStackRecommendations",
  "monetizationStrategy",
  "mvpScope",
  "architectureOverview",
  "designDirection",
] as const;

export function composeBlueprintMarkdown(blueprint: Blueprint, appName?: string): string {
  const parts: string[] = [];

  parts.push(`# ${appName || "App"} Blueprint\n`);
  parts.push(`*Generated by Shipright*\n`);
  parts.push("---\n");

  for (const key of SECTION_ORDER) {
    const content = blueprint[key as keyof Blueprint] as string | undefined;
    if (content) {
      parts.push(`# ${SECTION_TITLES[key]}\n`);
      parts.push(content);
      parts.push("\n---\n");
    }
  }

  return parts.join("\n");
}
